export const INDEX_MARKER = "<!-- generated by d4 second brain; do not edit -->";
export const MAP_TEMPLATE = "# Second brain\n\n@INDEX.md\n@MEMORY.md\n";
export const contentHash = (text: string) =>
  NodeCrypto.createHash("sha256").update(text).digest("hex");
export const kindForPath = (file: string): BrainNoteKind => {
  const folder = file.split("/")[0];
  return folder === "people"
    ? "person"
    : folder === "projects"
      ? "project"
      : folder === "decisions"
        ? "decision"
        : folder === "learnings"
          ? "learning"
          : "note";
};
export const validName = (file: string) =>
  ["AGENTS.md", "CLAUDE.md", "MEMORY.md", "LEARNINGS.md", "INDEX.md", "README.md"].includes(file) ||
  file
    .split("/")
    .every((part, i, parts) =>
      new RegExp(
        i === parts.length - 1 ? "^[a-z0-9]+(?:-[a-z0-9]+)*\\.md$" : "^[a-z0-9]+(?:-[a-z0-9]+)*$",
      ).test(part),
    );

function scalar(raw: string): string | number {
  const value = raw.trim();
  if (value.startsWith('"')) {
    const parsed: unknown = JSON.parse(value);
    if (typeof parsed !== "string") throw new SecondBrainError({ code: "malformed" });
    return parsed;
  }
  if (value.startsWith("'")) {
    if (!/^'(?:[^']|'')*'$/.test(value)) throw new SecondBrainError({ code: "malformed" });
    return value.slice(1, -1).replaceAll("''", "'");
  }
  if (/^[!&*{|>[\]}]/.test(value)) throw new SecondBrainError({ code: "malformed" });
  return /^\d+$/.test(value) ? Number(value) : value.replace(/\s+#.*$/, "");
}
function list(raw: string): Array<string | number> {
  const parts = raw.match(/"(?:[^"\\]|\\.)*"|'(?:[^']|'')*'|[^,]+/g) ?? [];
  return parts.map(scalar);
}
export function parseNote(file: string, content: string) {
  try {
    const lines = content.split(/\r?\n/);
    const raw: Record<string, unknown> = {};
    let bodyStart = 0;
    const frontmatter = lines[0] === "---";
    if (frontmatter) {
      const end = lines.indexOf("---", 1);
      if (end < 0 || end > 256) throw new SecondBrainError({ code: "malformed" });
      bodyStart = end + 1;
      let current = "";
      for (const line of lines.slice(1, end)) {
        if (!line.trim() || line.trimStart().startsWith("#")) continue;
        const item = /^\s+-\s+(.*)$/.exec(line);
        if (item) {
          const items = raw[current];
          if (!Array.isArray(items)) throw new SecondBrainError({ code: "malformed" });
          items.push(scalar(item[1]!));
          continue;
        }
        const match = /^([a-z]+):\s*(.*)$/.exec(line);
        if (!match || Object.hasOwn(raw, match[1]!))
          throw new SecondBrainError({ code: "malformed" });
        current = match[1]!;
        const value = match[2]!;
        raw[current] =
          value === ""
            ? []
            : value.startsWith("[") && value.endsWith("]")
              ? list(value.slice(1, -1))
              : scalar(value);
      }
    }
    const metadata = decodeBrainNoteMetadata(raw);
    const title =
      metadata.title ??
      lines
        .slice(bodyStart)
        .find((line) => line.startsWith("# "))
        ?.slice(2)
        .trim() ??
      NodePath.posix.basename(file, ".md");
    const kind = metadata.kind ?? kindForPath(file);
    const hash = contentHash(content);
    const chunks: Array<{
      heading: string;
      startLine: number;
      endLine: number;
      text: string;
      hash: string;
    }> = [];
    const links: Array<{ target: string; fragment: string; line: number; relative: boolean }> = [];
    let heading = title;
    let start = bodyStart;
    let fence: string | undefined;
    let bytes = 0;
    const flush = (end: number) => {
      const text = lines.slice(start, end).join("\n");
      if (text.trim())
        chunks.push({ heading, startLine: start + 1, endLine: end, text, hash: contentHash(text) });
      start = end;
      bytes = 0;
    };
    for (let i = bodyStart; i < lines.length; i++) {
      const line = lines[i]!;
      const marker = /^\s{0,3}(`{3,}|~{3,})/.exec(line)?.[1];
      if (marker) {
        if (!fence) fence = marker;
        else if (marker[0] === fence[0] && marker.length >= fence.length) fence = undefined;
      } else if (!fence) {
        const h = /^(#{1,6})\s+(.+)$/.exec(line);
        if (h) {
          flush(i);
          heading = h[2]!;
        }
        const visible = line.replace(/`[^`]*`/g, "");
        for (const match of visible.matchAll(
          /\[\[([^\]|]+)(?:\|[^\]]*)?\]\]|\[[^\]]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g,
        )) {
          const target = match[1] ?? match[2]!;
          if (/^[a-z]+:/i.test(target) || target.startsWith("//")) continue;
          const [name, fragment = ""] = target.split("#", 2);
          links.push({
            target: name || file,
            fragment,
            line: i + 1,
            relative: match[2] !== undefined && !!name,
          });
        }
      }
      if (bytes + Buffer.byteLength(line) > 32768 && i > start) flush(i);
      if (Buffer.byteLength(line) > 32768) {
        flush(i);
        let segment = "";
        let segmentBytes = 0;
        for (const character of line) {
          const size = Buffer.byteLength(character);
          if (segmentBytes + size > 32768) {
            chunks.push({
              heading,
              startLine: i + 1,
              endLine: i + 1,
              text: segment,
              hash: contentHash(segment),
            });
            segment = "";
            segmentBytes = 0;
          }
          segment += character;
          segmentBytes += size;
        }
        if (segment)
          chunks.push({
            heading,
            startLine: i + 1,
            endLine: i + 1,
            text: segment,
            hash: contentHash(segment),
          });
        start = i + 1;
        bytes = 0;
      } else bytes += Buffer.byteLength(line) + 1;
    }
    flush(lines.length);
    return {
      path: file,
      content,
      hash,
      title,
      kind,
      metadata,
      frontmatter,
      bytes: Buffer.byteLength(content),
      chunks,
      links,
    };
  } catch (error) {
    if (isBrainError(error)) throw error;
    throw new SecondBrainError({ code: "malformed" });
  }
}
export type NoteDocument = ReturnType<typeof parseNote>;
export function noteTemplate(kind: BrainNoteKind, title: string, id: string, date: string) {
  const sections = {
    note: ["Notes"],
    person: ["Details", "Meetings"],
    project: ["Status", "Next steps"],
    decision: ["Decision", "Rationale"],
    learning: ["Learning", "Sources"],
  };
  return `---\nschema: 1\nid: ${JSON.stringify(id)}\nkind: ${kind}\ntitle: ${JSON.stringify(title)}\ncreated: ${JSON.stringify(date)}\nupdated: ${JSON.stringify(date)}\nstatus: active\ntags: []\naliases: []\nsources: []\n---\n# ${title}\n\n${sections[kind].map((s) => `## ${s}\n`).join("\n")}`;
}
export function applyEdit(previous: string | null, edit: BrainEdit, date?: string) {
  if (edit.operation === "create" && previous !== null)
    throw new SecondBrainError({ code: "stale_revision" });
  if (edit.operation !== "create" && previous === null)
    throw new SecondBrainError({ code: "not_found" });
  if (edit.operation === "append") return `${previous!.trimEnd()}\n${edit.content}\n`;
  if (edit.operation === "str_replace" || edit.operation === "supersede") {
    if (!edit.oldStr || previous!.split(edit.oldStr).length !== 2)
      throw new SecondBrainError({ code: "malformed" });
    if (edit.operation === "str_replace") {
      if (edit.newStr === undefined) throw new SecondBrainError({ code: "malformed" });
      return previous!.replace(edit.oldStr, () => edit.newStr!);
    }
    if (!date || edit.oldStr.includes("\n") || !previous!.split(/\r?\n/).includes(edit.oldStr))
      throw new SecondBrainError({ code: "malformed" });
    return previous!.replace(
      edit.oldStr,
      () =>
        `~~${edit.oldStr}~~ (superseded ${date} by ${edit.content.replace(/\s+/g, " ")})\n${edit.content}`,
    );
  }
  if (edit.operation !== "replace-section" && edit.operation !== "patch_section")
    return edit.content;
  const lines = previous!.split(/\r?\n/);
  const headings: Array<{ i: number; level: number; title: string }> = [];
  let fence: string | undefined;
  for (const [i, line] of lines.entries()) {
    const marker = /^\s{0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (marker) {
      if (!fence) fence = marker;
      else if (marker[0] === fence[0] && marker.length >= fence.length) fence = undefined;
      continue;
    }
    if (fence) continue;
    const match = /^(#{1,6})\s+(.+)$/.exec(line);
    if (match) headings.push({ i, level: match[1]!.length, title: match[2]! });
  }
  const matches = headings.filter((h) => h.title === edit.heading);
  if (matches.length !== 1) throw new SecondBrainError({ code: "malformed" });
  const { i, level } = matches[0]!;
  const end = headings.find((h) => h.i > i && h.level <= level)?.i ?? lines.length;
  return [...lines.slice(0, i + 1), edit.content.trimEnd(), ...lines.slice(end)].join("\n");
}
export function generatedIndex(notes: ReadonlyArray<NoteDocument>) {
  const groups = new Map<BrainNoteKind, NoteDocument[]>();
  for (const note of notes.filter(
    (n) => !["INDEX.md", "AGENTS.md", "CLAUDE.md"].includes(n.path),
  )) {
    groups.set(note.kind, [...(groups.get(note.kind) ?? []), note]);
  }
  return `${INDEX_MARKER}\n# Index\n${[...groups]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([kind, entries]) =>
        `\n## ${kind}\n${entries
          .sort((a, b) => a.path.localeCompare(b.path))
          .map(
            (n) =>
              `- [${n.title.replace(/[[\]\r\n]/g, " ")}](${n.path}) — ${(n.chunks[0]?.text ?? "").replace(/\s+/g, " ").slice(0, 120)}`,
          )
          .join("\n")}\n`,
    )
    .join("")}`;
}

export const slug = (text: string) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
export function updateFrontmatter(content: string, date: string) {
  if (content.startsWith("---\r\n")) content = content.replaceAll("\r\n", "\n");
  if (!content.startsWith("---\n")) return content;
  const end = content.indexOf("\n---", 4);
  if (end < 0) return content;
  const header = content.slice(0, end);
  return (
    (/^updated:.*$/m.test(header)
      ? header.replace(/^updated:.*$/m, `updated: "${date}"`)
      : `${header}\nupdated: "${date}"`) + content.slice(end)
  );
}
export function nearSlug(left: string, right: string) {
  const a = slug(left).split("-").sort().join("-");
  const b = slug(right).split("-").sort().join("-");
  if (Math.abs(a.length - b.length) > 2) return false;
  let row = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 0; i < a.length; i++) {
    const next = [i + 1];
    for (let j = 0; j < b.length; j++)
      next.push(Math.min(next[j]! + 1, row[j + 1]! + 1, row[j]! + Number(a[i] !== b[j])));
    row = next;
  }
  return row[b.length]! <= 2;
}
